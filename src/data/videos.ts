/**
 * Helper function to retrieve all unlocked videos for a given date or elapsed day count.
 * All videos up to the current day are returned (at least 1, and grows daily).
 */
export function getUnlockedVideos(dayIndex: number): DailyVideoContent[] {
  const safeDay = Math.max(0, Math.min(dayIndex, ALL_VIDEOS.length - 1));
  // Return all videos up to today so previous videos stay available
  return ALL_VIDEOS.slice(0, safeDay + 1);
}

/**
 * Today's primary featured video for Day N
 */
export function getTodayFeaturedVideo(dayIndex: number): DailyVideoContent {
  const safeDay = Math.max(0, dayIndex % ALL_VIDEOS.length);
  return ALL_VIDEOS[safeDay];
}
